private func conversionsPage(_ style: DocStyle, _ catalog: Catalog, _ snippets: Snippets) -> String {
    var lines = pageTitle("Conversions")
    let stored = style == .docc ? "``Color`` in ``SRGB``" : "`Color<SRGB>`"
    lines.append("A coral \(stored), with red `0.8`, green `0.3`, and blue `0.2`, converted with \(style.code("ColorProtocol/converted(to:)")).")
    lines.append("")
    lines.append(swiftFence(snippets.conversions))
    lines.append("")
    lines.append("The last row is OKLCH converted back to sRGB. CIE76 from the original coral to that round trip is `\(formatDelta(catalog.roundTripDelta))`.")
    lines.append("")
    lines.append(markdownTable(["Space", "Components"], catalog.coordinateRows))
    lines.append("")
    lines.append("Hue is degrees. A neutral color has no hue, and the table would say `none`. Components are not clamped, so a conversion can leave the destination gamut and still be stored.")
    lines.append("")
    lines.append(closing(style, seen: "Conversions"))
    return joined(lines)
}

private func interpolationPage(_ style: DocStyle, _ catalog: Catalog) -> String {
    var lines = pageTitle("Interpolation")
    lines.append("\(style.code("ColorProtocol/interpolated(toward:amount:in:)")) converts both colors into the space you name, then mixes the components. Hue takes the shorter arc. A neutral color does not pull the mix toward hue `0`.")
    lines.append("")
    lines.append(style.image(catalog.interpolation))
    lines.append("")
    lines.append(catalog.interpolationCaption)
    lines.append("")
    lines.append(style.image(catalog.lightness))
    lines.append("")
    lines.append(catalog.lightnessCaption)
    lines.append("")
    lines.append(style.image(catalog.hue))
    lines.append("")
    lines.append(catalog.hueCaption)
    lines.append("")
    lines.append("Amount `0` and `1` return the original components in the destination space. Any other amount may extrapolate. The tiles above are drawn after clamping to the sRGB cube. The numbers in the library are not clamped.")
    lines.append("")
    lines.append(closing(style, seen: "Interpolation"))
    return joined(lines)
}

private func contrastPage(_ style: DocStyle, _ catalog: Catalog, _ snippets: Snippets) -> String {
    var lines = pageTitle("Contrast")
    lines.append("\(style.code("ColorProtocol/contrastRatio(against:)")) converts both colors to opaque sRGB and returns the WCAG 2 ratio `(L1 + 0.05) / (L2 + 0.05)`. Black on white is `21`.")
    lines.append("")
    lines.append(style.image(catalog.contrast))
    lines.append("")
    lines.append("The letters are the foreground. The caption is the ratio, drawn in ink so it stays readable when the sample itself fails contrast.")
    lines.append("")
    lines.append(contrastTable(catalog))
    lines.append("")
    lines.append(swiftFence(snippets.contrast))
    lines.append("")
    lines.append("`#767676` on white is `\(formatRatio(catalog.grayOnWhite))`. WCAG defines the ratio for in-gamut sRGB. Out-of-gamut channels are not clamped and can produce a ratio outside `1...21`.")
    lines.append("")
    lines.append(closing(style, seen: "Contrast"))
    return joined(lines)
}

private func differencePage(_ style: DocStyle, _ catalog: Catalog, _ snippets: Snippets) -> String {
    var lines = pageTitle("Difference")
    lines.append("\(style.code("ColorProtocol/deltaE76(to:)")) is the Euclidean distance in CIELAB. It is not CIEDE2000.")
    lines.append("")
    lines.append(style.image(catalog.difference))
    lines.append("")
    lines.append(differenceTable(catalog))
    lines.append("")
    lines.append(swiftFence(snippets.difference))
    lines.append("")
    lines.append("Red against orange is the middle pair. A small step in encoded gray is a small CIE76 distance. Blue against yellow is large because their `a*` and `b*` point in opposite directions.")
    lines.append("")
    lines.append(closing(style, seen: "Difference"))
    return joined(lines)
}

